"""Turn the dashboards' sample data (JSON) into seed.sql for the reporting database.

Usage: python3 build_seed.py <P2 dashboard data dir> <P4 dashboard data dir> > seed.sql
All rows are made-up sample data for illustration; none of it is Alcovia's.
"""
import json
import sys
from pathlib import Path

p2, p4 = Path(sys.argv[1]), Path(sys.argv[2])
load = lambda d, name: json.loads((d / f"sample_{name}.json").read_text())


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


out = ["-- Sample data (made up, for illustration). Generated by build_seed.py.", "BEGIN;"]


def insert(table, cols, rows):
    rows = list(rows)
    if not rows:
        return
    out.append(f"-- {table}: {len(rows)} rows")
    for i in range(0, len(rows), 500):
        values = ",\n".join("(" + ", ".join(lit(v) for v in r) + ")" for r in rows[i:i + 500])
        out.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{values};")


# ---------------- ops: shared settings, advisors ----------------
targets = {t["key"]: t for t in load(p2, "targets")}
as_of = targets["as_of"]["value"]
insert("ops.settings", ["key", "label", "value_num", "value_text"], [
    ("as_of", "Data as of", None, as_of),
    ("first_month", "First month with data", None, targets["first_month"]["value"]),
    ("days_to_decide", targets["days_to_decide"]["label"], targets["days_to_decide"]["value"], None),
    # colour thresholds from the P2 doc (not in the dashboard's targets file)
    ("invoice_amber", "Invoice amber from (days unpaid)", 5, None),
    ("invoice_red", "Invoice red from (days unpaid)", 10, None),
    ("renewal_yellow", "Trial renewal yellow from (days left)", 30, None),
    ("renewal_amber", "Trial renewal amber from (days left)", 15, None),
    ("renewal_red", "Trial renewal red from (days left)", 7, None),
])
students_p4 = load(p4, "students")
advisors = sorted({s["advisor"] for s in students_p4})
advisor_id = {a: i for i, a in enumerate(advisors, 1)}
insert("ops.advisors", ["advisor_id", "name"], [(i, a) for a, i in advisor_id.items()])

# ---------------- events ----------------
delivery = load(p4, "delivery")
types = [("Public workshop", "Month")]
for d in delivery:
    if d["item"] not in [n for n, _ in types]:
        types.append((d["item"], d["level"]))
type_id = {n: i for i, (n, _) in enumerate(types, 1)}
insert("events.event_types", ["event_type_id", "name", "level"], [(type_id[n], n, lv) for n, lv in types])
insert("events.events", ["event_id", "event_type_id", "held_on", "venue", "seats_sold", "attended"],
       [(w["workshop_id"], type_id["Public workshop"], w["date"], w["venue"], w["seats_sold"], w["attended"]) for w in load(p2, "workshops")])
insert("events.delivery_month", ["month", "event_type_id", "planned", "held", "attendance_pct", "ratings_n", "rating_avg", "response_rate"],
       [(d["month"] + "-01", type_id[d["item"]], d["planned"] or 0, d["held"] or 0, d["attendance_pct"], d["ratings_n"] or 0, d["rating_avg"], d["response_rate"])
        for d in delivery])

# ---------------- ads (restricted) ----------------
money_keys = ["revenue_month", "full_month", "trial_month", "seats_month", "full_price", "trial_price", "seat_price",
              "cpql", "cost_per_seat", "venue", "frequency"]
insert("ads.targets", ["key", "label", "value_num"],
       [(k, targets[k]["label"], targets[k]["value"]) for k in money_keys] + [("drop_weeks", "Weeks over the ceiling before Drop", 2)])

ads_daily = load(p2, "ads_daily")
campaigns = sorted({(r["campaign"], r["type"]) for r in ads_daily})
campaign_id = {name: i for i, (name, _) in enumerate(campaigns, 1)}
insert("ads.campaigns", ["campaign_id", "name", "campaign_type"], [(i, n, t) for i, (n, t) in enumerate(campaigns, 1)])
ads = {}
for r in ads_daily:
    a = ads.setdefault(r["ad"], {"campaign": r["campaign"], "first": r["date"], "last": r["date"]})
    a["first"], a["last"] = min(a["first"], r["date"]), max(a["last"], r["date"])
ad_id = {n: i for i, n in enumerate(sorted(ads), 1)}
# the sample starts in August; ads that ran before then show their first day in the sample
insert("ads.ads", ["ad_id", "campaign_id", "name", "started_on", "ended_on"],
       [(ad_id[n], campaign_id[a["campaign"]], n, a["first"], None if a["last"] >= as_of else a["last"]) for n, a in sorted(ads.items())])
insert("ads.ad_daily", ["day", "ad_id", "spend", "impressions", "clicks", "frequency"],
       [(r["date"], ad_id[r["ad"]], r["spend"], r["impressions"], r["clicks"], r["frequency"]) for r in ads_daily])
insert("ads.page_daily", ["day", "page", "visitors", "dropoffs", "load_mobile_s", "load_desktop_s"],
       [(r["date"], r["page"], r["visitors"], r["dropoffs"], r["load_mobile_s"], r["load_desktop_s"]) for r in load(p2, "pages")])

# ---------------- leads ----------------
leads = load(p2, "leads")
insert("leads.leads", ["lead_id", "created_on", "entry_path", "source", "ad_id", "workshop_id", "qualified_on", "call_booked_on",
                       "call_attended_on", "interview_on", "interview_outcome", "architect_on", "closed_on", "closed_reason"],
       [(l["lead_id"], l["created"], l["path"], l["source"], ad_id.get(l["ad"]), l["workshop_id"], l["qualified"], l["call_booked"],
         l["call_attended"], l["interview"], l["interview_outcome"], l["architect"], l["closed"], l["closed_reason"]) for l in leads])

# ---------------- students ----------------
# Families who paid (trial or full) are on the platform: one family and one student each, linked to their lead.
# 'Family 0442' in the sample = lead L0442 → family F0442, student S0442.
invoices = load(p2, "invoices")
inv_lead = {i["invoice_id"]: "L" + i["family"].split()[-1] for i in invoices}
paid = sorted({inv_lead[i["invoice_id"]] for i in invoices if i["paid"]})
fam = lambda lead: "F" + lead[1:]
stu = lambda lead: "S" + lead[1:]
# the 20 students of the P4 sample joined before lead tracking: their own families, no lead
insert("students.families", ["family_id", "lead_id", "city"],
       [(fam(l), l, None) for l in paid] + [("F" + s["student_id"][1:], None, None) for s in students_p4])
insert("students.students", ["student_id", "family_id", "name", "grade", "advisor_id", "startup", "career_roadmap", "health_connected"],
       [(stu(l), fam(l), None, None, None, None, None, False) for l in paid] +
       [(s["student_id"], "F" + s["student_id"][1:], s["student"], None, advisor_id[s["advisor"]], s["startup"], s["career_roadmap"], s["health_connected"])
        for s in students_p4])

trials = {"L" + t["trial_id"][2:]: t for t in load(p2, "trials")}
enrol = []
for i in sorted(invoices, key=lambda x: x["paid"] or ""):
    if not i["paid"]:
        continue
    lead = inv_lead[i["invoice_id"]]
    if i["plan"] == "Full program":
        enrol.append((stu(lead), "Full program", i["paid"], None, "Active", False))
    else:
        t = trials[lead]
        enrol.append((stu(lead), "Trial", t["start"], t["end"], t["status"], False))
        if t["status"] == "Renewed":
            enrol.append((stu(lead), "Full program", t["end"], None, "Active", True))
insert("students.enrolments", ["student_id", "plan", "started_on", "ends_on", "status", "via_trial"], enrol)

insert("students.student_month", ["student_id", "month", "counted_min", "quiz_participation_pct", "quiz_accuracy_pct", "syllabus_pct", "pace_pct",
                                  "readiness", "attendance_pct", "rating_given", "task_completion_pct", "deadline_adherence_pct", "sleep_hrs", "active_days_pct"],
       [(k["student_id"], k["month"] + "-01", k["counted_min"], k["quiz_participation"], k["quiz_accuracy"], k["syllabus_pct"], k["pace_pct"],
         k["readiness"], k["attendance_pct"], k["rating_given"], k["task_completion"], k["deadline_adherence"], k["sleep_hrs"], k["active_days_pct"])
        for k in load(p4, "student_kpis")])
insert("students.student_week", ["student_id", "week", "counted_min", "sleep_hrs", "active_min"],
       [(w["student_id"], w["week"], w["counted_min"], w["sleep_hrs"], w["active_min"]) for w in load(p4, "weekly")])
insert("students.subject_progress", ["student_id", "subject", "syllabus_pct", "pace_pct", "readiness", "latest_score", "target_score"],
       [(s["student_id"], s["subject"], s["syllabus_pct"], s["pace_pct"], s["readiness"], s["latest_score"], s["target"]) for s in load(p4, "subjects")])
insert("students.soft_skill_scores", ["student_id", "skill", "first_score", "latest_score"],
       [(s["student_id"], s["skill"], s["first_workshop"], s["latest_workshop"]) for s in load(p4, "soft_skills")])
insert("students.milestones", ["milestone_id", "student_id", "track", "milestone", "due_month", "status"],
       [(m["milestone_id"], m["student_id"], m["track"], m["milestone"], m["month_due"] + "-01", m["status"]) for m in load(p4, "milestones")])
insert("events.family_deliverables", ["student_id", "item", "planned", "done", "status"],
       [(p["student_id"], p["item"], p["planned"], p["done"], p["status"]) for p in load(p4, "parent_view")])
student_advisor = {s["student_id"]: advisor_id[s["advisor"]] for s in students_p4}
insert("ops.alerts", ["alert_id", "student_id", "advisor_id", "raised_on", "alert_type", "detail", "status"],
       [(a["alert_id"], a["student_id"], student_advisor[a["student_id"]], a["date"], a["type"], a["detail"], a["status"]) for a in load(p4, "alerts")])

# ---------------- revenue (restricted) ----------------
insert("revenue.invoices", ["invoice_id", "lead_id", "plan", "amount", "issued_on", "paid_on"],
       [(i["invoice_id"], inv_lead[i["invoice_id"]], i["plan"], i["amount"], i["issued"], i["paid"]) for i in invoices])
pay_rows = []
for p in load(p2, "payments"):
    is_inv = p["ref"].startswith("INV")
    pay_rows.append((p["payment_id"], p["date"], "Trial renewal" if p["type"] == "Renewal" else p["type"], p["amount"],
                     inv_lead[p["ref"]] if is_inv else None, p["ref"] if is_inv else None, None if is_inv else p["ref"],
                     p["path"], ad_id.get(p["ad"])))
insert("revenue.payments", ["payment_id", "paid_on", "payment_type", "amount", "lead_id", "invoice_id", "workshop_id", "entry_path", "ad_id"], pay_rows)

# ---------------- raw tables (production grain) for the 20 P4 sample students ----------------
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_raw_sample  # noqa: E402
build_raw_sample.build(lambda name: load(p4, name), insert, type_id)

out.append("COMMIT;")
print("\n".join(out))
